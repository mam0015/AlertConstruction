// One-off: collects the prices the older tools used to carry, so the Owner can choose to load them as a starting point.
//   * Electrical / Plumbing / Cladding: the catalogue inside supabase/functions/analyse-plan/index.ts (the older AI plan estimator's own price list)
//   * Renovation planning allowances: renovation-budget/rates.js (before it cleared them)
// They are written to db/estimate-starter.ts, which only the server imports: the numbers are never part of a page or script a browser downloads.
// The Owner or Admin has to press "Load previous prices", look them over and save them; nothing is priced from them automatically.
import { readFileSync, writeFileSync } from "node:fs";

const read = (file) => readFileSync(new URL(`../${file}`, import.meta.url), "utf8");
const fn = read("supabase/functions/analyse-plan/index.ts");
const catalogue = read("app/estimate-tools/catalogue.data.mjs");

// Names in the app's catalogue, in order, per trade (read from the generated catalogue.ts).
const names = {};
for (const trade of ["electrical", "plumbing", "cladding"]) {
  const block = catalogue.slice(catalogue.indexOf(`"id": "${trade}"`));
  const end = block.indexOf('"id": "', 10);
  names[trade] = [...(end > 0 ? block.slice(0, end) : block).matchAll(/"key": "[a-z]+:\d+",\s*"name": "((?:[^"\\]|\\.)*)"/g)].map((match) => JSON.parse(`"${match[1]}"`));
}

const starter = {};
const report = [];
for (const trade of ["electrical", "plumbing", "cladding"]) {
  const start = fn.indexOf(`${trade}:{`, fn.indexOf("const TRADE_CONFIG"));
  const catalogStart = fn.indexOf("catalog:[", start);
  const catalogEnd = fn.indexOf("]\n", catalogStart);
  const entries = [...fn.slice(catalogStart, catalogEnd).matchAll(/\{name:"((?:[^"\\]|\\.)*)",rate:([0-9.]+)\}/g)].map((match) => ({ name: JSON.parse(`"${match[1]}"`), rate: Number(match[2]) }));
  let matched = 0;
  entries.forEach((entry, index) => {
    if (names[trade][index] === entry.name) { starter[`${trade}:${index}`] = entry.rate; matched += 1; } else report.push(`${trade}:${index} name differs: "${entry.name}" vs "${names[trade][index]}"`);
  });
  report.push(`${trade}: ${matched}/${entries.length} prices matched to ${names[trade].length} items`);
}

// Renovation allowances (the numbers before the old tool cleared them).
const rates = read("renovation-budget/rates.js").replace(/Object\.values\(allowances\)\.forEach\([^\n]*\n/, "");
const scope = {};
new Function("window", rates)(scope);
let allowances = 0;
for (const [group, items] of Object.entries(scope.ACRenovationRates.allowances)) for (const [id, item] of Object.entries(items)) { starter[`renovation:${group}:${id}`] = item.rate; allowances += 1; }
report.push(`renovation allowances: ${allowances}`);

writeFileSync(new URL("../db/estimate-starter.ts", import.meta.url), `// Generated by scripts/extract-starter-prices.mjs. SERVER ONLY: do not import this from a page or component.
// The prices the older tools carried (dollars ex GST per unit). The Owner or Admin can load them as a starting point and must save them as the
// company's own; they are never applied automatically.
export const STARTER_PRICES: Record<string, number> = ${JSON.stringify(starter, null, 2)};
`);
console.log(report.join("\n"));
