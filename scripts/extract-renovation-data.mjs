// One-off: reads the older Renovation Budget tool (renovation-budget/rates.js and app.js) and writes
//   app/estimate-tools/renovation-data.mjs   the questions, areas, items and the starting allowances
//   app/estimate-tools/renovation-lines.mjs  the rules that turn answers into priced lines (copied from the old buildLines, with the price lookup replaced)
// Nothing is guessed: the data is evaluated from the old source and the rules are the old source text.
import { readFileSync, writeFileSync } from "node:fs";

const read = (file) => readFileSync(new URL(`../${file}`, import.meta.url), "utf8");
const rates = read("renovation-budget/rates.js");
const app = read("renovation-budget/app.js");

// ---- rates.js: evaluate it with the "clear every price" line removed, so the original allowance numbers are still there.
const cleared = rates.replace(/Object\.values\(allowances\)\.forEach\([^\n]*\n/, "");
if (cleared === rates) throw new Error("could not find the line that clears the allowance prices");
const window = {};
new Function("window", cleared)(window);
const R = window.ACRenovationRates;

// ---- app.js: the category / area / question definitions are plain data between two markers.
const start = app.indexOf("const categories=[");
const end = app.indexOf("function freshState()");
if (start < 0 || end < 0) throw new Error("could not find the question definitions");
const defs = new Function(`${app.slice(start, end)}\nreturn {categories,scopeInfo,questions};`)();

// Items: every priced thing gets a stable key. Trade items keep "electrical:N" (the same keys as the price list), allowances become "renovation:group:name".
const verified = {};
for (const [trade, items] of Object.entries(R.verified)) {
  verified[trade] = Object.fromEntries(Object.entries(items).map(([id, item]) => [id, { key: item.catalogueKey, name: item.name, unit: item.unit }]));
}
const allowances = {};
const suggested = {};
for (const [group, items] of Object.entries(R.allowances)) {
  allowances[group] = Object.fromEntries(Object.entries(items).map(([id, item]) => {
    const key = `renovation:${group}:${id}`;
    suggested[key] = item.rate;
    return [id, { key, name: item.name, unit: item.unit }];
  }));
}

const data = `// Generated by scripts/extract-renovation-data.mjs from the older Renovation Budget tool. Questions, areas and item names only;
// No prices are in this file: browsers download it. The previous planning numbers live in db/estimate-starter.ts (server only).
export const CATEGORIES = ${JSON.stringify(defs.categories, null, 2)};
export const SCOPE_INFO = ${JSON.stringify(defs.scopeInfo, null, 2)};
export const QUESTIONS = ${JSON.stringify(defs.questions, null, 2)};
export const VERIFIED = ${JSON.stringify(verified, null, 2)};
export const ALLOWANCES = ${JSON.stringify(allowances, null, 2)};
export const QUALITY_MULTIPLIERS = ${JSON.stringify(R.qualityMultipliers)};
export const QUALITY_LABELS = ${JSON.stringify(R.qualityLabels)};
export const ALLOWANCE_KEYS = Object.values(ALLOWANCES).flatMap((group) => Object.values(group).map((item) => item.key));
export const ALLOWANCE_GROUP_LABELS = { demolition: "Demolition", waterproofing: "Waterproofing", tiling: "Tiling", cabinetry: "Cabinetry", benchtop: "Benchtops", fixtures: "Fixtures", carpentry: "Carpentry", plastering: "Plastering", painting: "Painting", flooring: "Flooring", exterior: "Exterior", professional: "Professional and site costs" };
`;
writeFileSync(new URL("../app/estimate-tools/renovation-data.mjs", import.meta.url), data);

// ---- the rules: the old buildLines body from `const A=...` to `return lines;`
const bodyStart = app.indexOf("const A=R.allowances,V=R.verified;");
const bodyEnd = app.indexOf("return lines;", bodyStart);
if (bodyStart < 0 || bodyEnd < 0) throw new Error("could not find the pricing rules");
const body = app.slice(bodyStart, bodyEnd);
const lines = `// Generated by scripts/extract-renovation-data.mjs. The rules below are the older Renovation Budget tool's own (buildLines), unchanged;
// only the price lookup differs: a price comes from the company price list, and an item without a price is collected in \`missing\`
// instead of being priced from a hidden default. Nothing is calculated from a made-up number.
import { ALLOWANCES, QUALITY_MULTIPLIERS, VERIFIED } from "./renovation-data.mjs";

const number = (value) => Math.max(0, Number(value) || 0);
const yes = (value) => String(value) === "yes";
export const defaultPriority = (scope) => (["bathroom", "kitchen"].includes(scope) ? "must" : "important");

// state: { scopes: string[], priorities: {scope: "must"|"important"|"optional"}, answers: {id: value}, project: { quality } }
// rateOf(itemKey) -> dollars per unit, or null when the company has not set a price for it.
export function buildLines(state, rateOf, qualityOverride) {
  const quality = qualityOverride || state.project?.quality || "standard";
  const qualityFactor = QUALITY_MULTIPLIERS[quality] || 1;
  const lines = [];
  const missing = new Map();
  const priority = (scope) => state.priorities?.[scope] || defaultPriority(scope);
  const readAnswer = (id) => state.answers?.[id];
  function add(scope, trade, item, qty, source, options = {}) {
    qty = number(qty);
    if (!qty) return;
    const base = rateOf(item.key);
    if (base === null || base === undefined || !Number.isFinite(Number(base))) { missing.set(item.key, item); return; }
    const rate = Number(base) * (source === "allowance" && options.finishSensitive ? qualityFactor : 1);
    lines.push({ id: \`\${scope}_\${trade}_\${lines.length}\`, scope, trade, key: item.key, name: item.name, qty, unit: item.unit, rate, builder: rate * qty, priority: priority(scope), critical: !!options.critical, note: options.note || "" });
  }
  const ac = (scope, trade, item, qty, options) => add(scope, trade, item, qty, "ac", options);
  const allowance = (scope, trade, item, qty, options) => add(scope, trade, item, qty, "allowance", options);
  const A = ALLOWANCES, V = VERIFIED;
  ${body.slice(body.indexOf("\n") + 1).trim()}
  return { lines, missing: [...missing.values()] };
}

// Totals: the pricing subtotal, the builder margin, GST, then the contingency on top.
export function totalsFor(lines, { budget = 0, contingency = 15, marginPercent = 20 } = {}) {
  const builderEx = lines.reduce((sum, line) => sum + line.builder, 0);
  const margin = builderEx * (marginPercent / 100);
  const customerEx = builderEx + margin;
  const gst = customerEx * 0.1;
  const worksInc = customerEx + gst;
  const contingencyValue = worksInc * (contingency / 100);
  const grand = worksInc + contingencyValue;
  return { builderEx, margin, customerEx, gst, worksInc, contingency: contingencyValue, grand, budget, remaining: budget - grand, over: Math.max(0, grand - budget) };
}

// Do now / do later / optional, within the budget (after the contingency is set aside). Must-have and critical work first.
export function recommendations(lines, totals, { contingency = 15, marginPercent = 20 } = {}) {
  const rank = { must: 0, important: 1, optional: 2 };
  const sorted = [...lines].sort((a, b) => (a.priority === "optional") - (b.priority === "optional") || (b.critical - a.critical) || (rank[a.priority] - rank[b.priority]) || (b.builder - a.builder));
  const available = Math.max(0, totals.budget / (1 + contingency / 100));
  let used = 0;
  const now = [], later = [], optional = [];
  for (const line of sorted) {
    const customerCost = line.builder * (1 + marginPercent / 100) * 1.1;
    if (line.priority === "optional") { optional.push({ ...line, customerCost }); continue; }
    if (used + customerCost <= available) { now.push({ ...line, customerCost }); used += customerCost; } else later.push({ ...line, customerCost });
  }
  return { now, later, optional };
}
`;
writeFileSync(new URL("../app/estimate-tools/renovation-lines.mjs", import.meta.url), lines);
