// One-off: reads the three older calculator pages (electrical/, plumbing/, cladding/) and writes the item lists (sections, names, descriptions,
// units) to app/estimate-tools/catalogue.ts. Item numbers follow the page order, which is also the order in shared/catalogue-defaults.js
// ("electrical:0", "plumbing:12", …), so the same keys identify the same items everywhere. No prices are read or written: the older pages
// never contained any ("Secure verified rate required"); the company types its own into the app.
import { readFileSync, writeFileSync } from "node:fs";

const decode = (text) => text.replace(/<[^>]+>/g, "").replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#0?39;/g, "'").replace(/&nbsp;/g, " ").replace(/\s+/g, " ").trim();
const page = (trade) => readFileSync(new URL(`../${trade}/index.html`, import.meta.url), "utf8");
const defaults = readFileSync(new URL("../shared/catalogue-defaults.js", import.meta.url), "utf8");

function defaultNames(trade) {
  const block = defaults.match(new RegExp(`add\\('${trade}',\\[([\\s\\S]*?)\\n  \\]\\);`))[1];
  return [...block.matchAll(/\['((?:[^'\\]|\\.)*)'(?:,'([^']*)')?\]/g)].map((match) => ({ name: match[1].replace(/\\'/g, "'"), unit: match[2] ?? "each" }));
}

function read(trade) {
  const html = page(trade);
  const names = defaultNames(trade);
  // Sections: <div class="section"> (electrical) or <details class="section"> (plumbing, cladding); each holds the item rows that follow its heading.
  const parts = html.split(/<(?:div|details) class="section"/).slice(1);
  let index = 0;
  const sections = [];
  for (const part of parts) {
    const heading = decode(part.match(/<h2>([\s\S]*?)<\/h2>/)?.[1] ?? "");
    const blurb = decode(part.match(/<h2>[\s\S]*?<\/h2>\s*<p>([\s\S]*?)<\/p>/)?.[1] ?? "").replace(/\s*Current (?:supplier-derived|verified) rates load only from the protected company catalogue\.?/i, "").trim();
    const items = [];
    for (const row of part.split('<div class="item"').slice(1)) {
      const nameHtml = row.match(/<div class="item-name">([\s\S]*?)<\/div>/)?.[1] ?? "";
      let detail = decode(row.match(/<div class="item-desc">([\s\S]*?)<\/div>/)?.[1] ?? "");
      // The older pages repeated "the rate loads from the protected company catalogue" on many rows; that is not a description of the work.
      if (/protected company catalogue|server-verified/i.test(detail)) detail = "";
      const shown = decode(nameHtml.replace(/<span class="tag">[^<]*<\/span>/g, ""));
      const known = names[index];
      if (!known) throw new Error(`${trade}: more items on the page than in catalogue-defaults.js (item ${index})`);
      items.push({ key: `${trade}:${index}`, name: known.name, shown, detail, unit: known.unit });
      index += 1;
    }
    if (items.length) sections.push({ title: heading, blurb, items });
  }
  if (index !== names.length) throw new Error(`${trade}: page has ${index} items, catalogue-defaults.js has ${names.length}`);
  return sections;
}

const trades = {
  electrical: { label: "Electrical", blurb: "Lighting, power points, switches, bathroom and data work.", decimal: false },
  plumbing: { label: "Plumbing", blurb: "Rough-in packages, fit-off fixtures, gas, drainage and extras.", decimal: false },
  cladding: { label: "Cladding", blurb: "Thermory C32 cladding, corner mouldings, delivery and invoice packages.", decimal: true },
};
const out = Object.entries(trades).map(([id, info]) => ({ id, ...info, sections: read(id) }));
const data = `// Generated by scripts/extract-estimate-catalogue.mjs from the older calculator pages. Item identity and order only: no prices are stored here.
// Keys ("electrical:0") match shared/catalogue-defaults.js, so a price saved for a key always belongs to the same item.
export const TRADES = ${JSON.stringify(out, null, 2)};
`;
const typed = `// Typed view of catalogue.data.mjs (generated by scripts/extract-estimate-catalogue.mjs).
import { TRADES as DATA } from "./catalogue.data.mjs";

export type CatalogueItem = { key: string; name: string; shown: string; detail: string; unit: string };
export type CatalogueSection = { title: string; blurb: string; items: CatalogueItem[] };
export type TradeId = "electrical" | "plumbing" | "cladding";
export type Trade = { id: TradeId; label: string; blurb: string; decimal: boolean; sections: CatalogueSection[] };

export const TRADES = DATA as Trade[];
export const ALL_ITEMS = TRADES.flatMap((trade) => trade.sections.flatMap((section) => section.items.map((item) => ({ ...item, trade: trade.id }))));
export const ITEM_KEYS = new Set(ALL_ITEMS.map((item) => item.key));
`;
writeFileSync(new URL("../app/estimate-tools/catalogue.data.mjs", import.meta.url), data);
writeFileSync(new URL("../app/estimate-tools/catalogue.ts", import.meta.url), typed);
