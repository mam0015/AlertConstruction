// One-off: copies the per-trade reading rules of the older AI plan estimator (supabase/functions/analyse-plan/index.ts): what drawings count as
// enough, how to count, and which catalogue items may stand in for a removal or a move. The older function's prices are NOT copied here.
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(new URL("../supabase/functions/analyse-plan/index.ts", import.meta.url), "utf8");
const start = source.indexOf("const TRADE_CONFIG");
const open = source.indexOf("={", start) + 1;
const end = source.indexOf("\n};", open) + 2;
let literal = source.slice(open, end);
// Drop the price catalogues (name/rate pairs): only the rules are wanted.
literal = literal.replace(/catalog:\[[\s\S]*?\n\s*\]/g, "catalog:[]");
const config = new Function(`return ${literal};`)();
const rules = Object.fromEntries(Object.entries(config).map(([id, trade]) => [id, { label: trade.label, required: trade.required, rules: trade.rules, removed: trade.actionIndexes.removed, moved: trade.actionIndexes.moved }]));
writeFileSync(new URL("../app/estimate-tools/ai-rules.mjs", import.meta.url), `// Generated by scripts/extract-ai-rules.mjs from the older AI plan estimator. Reading rules only; no prices.
export const TRADE_RULES = ${JSON.stringify(rules, null, 2)};
`);
console.log(Object.entries(rules).map(([id, rule]) => `${id}: removed ${JSON.stringify(rule.removed)}, moved ${JSON.stringify(rule.moved)}, rules ${rule.rules.length} chars`).join("\n"));
